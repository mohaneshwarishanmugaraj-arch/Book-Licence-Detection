# 10. PARSE LLM JSON
# ============================================================

def parse_llm_json(llm_output):

    if not llm_output:

        return None

    cleaned = clean_llm_output(
        llm_output
    )

    try:

        result = json.loads(
            cleaned
        )

        result["method"] = "LLM"

        return result

    except json.JSONDecodeError:

        pass

    match = re.search(
        r"\{.*\}",
        cleaned,
        flags=re.DOTALL
    )

    if match:

        json_text = match.group(0)

        try:

            result = json.loads(
                json_text
            )

            result["method"] = "LLM"

            return result

        except json.JSONDecodeError:

            pass

    print(
        "\n[WARN] NVIDIA did not return valid JSON"
    )

    return {
        "license_name": "Unknown",
        "license_family": "Unknown",
        "copyright_holder": "",
        "copyright_status": "Unable to parse LLM response",
        "commercial_use": None,
        "modification_allowed": None,
        "redistribution_allowed": None,
        "attribution_required": None,
        "evidence": llm_output,
        "confidence": 0.0,
        "method": "LLM"
    }


