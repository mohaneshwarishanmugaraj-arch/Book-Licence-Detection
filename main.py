# 7. EXTRACT LICENSE EVIDENCE (for LLM fallback)
# ============================================================

def extract_license_related_text(
    full_text,
    context_before=4,
    context_after=5,
    max_characters=12000
):

    if not full_text:

        return ""

    lines = full_text.splitlines()

    relevant_blocks = []

    for i, line in enumerate(lines):

        line_lower = line.lower()

        matched = False

        for keyword in LICENSE_KEYWORDS:

            if keyword in line_lower:

                matched = True

                break

        if not matched:

            continue

        start = max(
            0,
            i - context_before
        )

        end = min(
            len(lines),
            i + context_after + 1
        )

        block = "\n".join(
            lines[start:end]
        ).strip()

        if block and block not in relevant_blocks:

            relevant_blocks.append(block)

    result = "\n\n".join(
        relevant_blocks
    )

    if len(result) > max_characters:

        result = result[:max_characters]

        result += (
            "\n\n[License evidence truncated]"
        )

    return result


