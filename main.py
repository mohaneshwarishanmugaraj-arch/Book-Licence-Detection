def main():

    print("\n==============================================")
    print("  AUTOMATIC PDF LICENSE & METADATA PIPELINE")
    print("  (Deterministic Rule Engine + LLM Fallback)")
    print("==============================================")

    # Initialize PostgreSQL Database Table & Indexes
    init_db()

    input_dir = "input"
    if not os.path.exists(input_dir):
        os.makedirs(input_dir, exist_ok=True)


    # Find all PDFs in input directory
    pdf_files = glob.glob(os.path.join(input_dir, "*.pdf"))

    if not pdf_files:
        print(f"\n[WARN] No PDF files found in '{input_dir}/' folder.")
        print(f"Please place your PDF file(s) in the '{input_dir}/' directory and run again.")
        return

    print(f"\nFound {len(pdf_files)} PDF file(s) in '{input_dir}/':")
    for idx, pdf in enumerate(pdf_files, 1):
        print(f"  {idx}. {os.path.basename(pdf)}")

    # Process each PDF automatically
    for pdf_path in pdf_files:
        try:
            process_pdf(pdf_path)
        except Exception as error:
            print(f"\n[ERROR] Failed to process {pdf_path}: {error}")

    print("\n==============================================")
    print("      ALL INPUT PDFs PROCESSED SUCCESSFULLY")
    print("==============================================")


