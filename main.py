# 15. PROCESS SINGLE PDF
# ============================================================

def process_pdf(pdf_path):

    print(
        "\n=============================================="
    )

    print(
        f"  PROCESSING DOCUMENT: {os.path.basename(pdf_path)}"
    )

    print(
        "=============================================="
    )

    # STEP 1: PARSE PDF
    parse_pdf(pdf_path)

    # STEP 2: BASIC METADATA
    print("\n========== BASIC METADATA ==========")
    basic_metadata = extract_basic_metadata(pdf_path)
    for key, value in basic_metadata.items():
        print(f"{key}: {value}")

    # STEP 3: LOAD JSON
    json_path = find_json_for_pdf(pdf_path)
    print("\n========== LOADING OPENDATALOADER JSON ==========")

    if not os.path.exists(json_path):
        raise FileNotFoundError(
            f"OpenDataLoader JSON not found: {json_path}"
        )

    pdf_json = load_json(json_path)
    print("[OK] JSON loaded successfully")

    # STEP 4: BUILD METADATA
    print("\n========== BUILDING METADATA ==========")
    final_metadata = build_metadata(basic_metadata, pdf_json)

    # STEP 5: EXTRACT FULL TEXT
    print("\n========== TEXT EXTRACTION ==========")
    full_text = extract_text_from_json(pdf_json)
    print(f"Extracted text length: {len(full_text)} characters")

    # STEP 6: PREVIEW
    show_text_preview(full_text, characters=3000)

    # STEP 7: PREPROCESS TEXT
    preprocessed_text = preprocess_text(
        full_text,
        max_pages=10,
        chars_per_page=3000
    )

    # STEP 8: LICENSE DETECTION (LLM PRIMARY + RULE-BASED FALLBACK)
    print("\n========== LICENSE DETECTION ==========")
    
    # Try LLM first to get the exact license details
    nvidia_ok = test_nvidia_connection()
    license_result = None
    
    if nvidia_ok:
        print("[INFO] Querying NVIDIA LLM for exact license detection...")
        license_text = extract_license_related_text(full_text)
        if license_text:
            print("\nLicense-related evidence found:\n")
            print(license_text)
            
            llm_output = detect_license_with_llm(license_text)
            print("\n========== RAW NVIDIA OUTPUT ==========")
            print(llm_output)
            
            license_result = parse_llm_json(llm_output)
            if license_result and license_result.get("license_name") != "Unknown":
                print("\n[OK] License detected by NVIDIA LLM")
                print_license_result(license_result)
            else:
                print("\n[INFO] LLM returned 'Unknown' license. Trying rule-based fallback...")
                license_result = None
        else:
            print("\n[WARN] No license-related evidence found for LLM. Trying rule-based...")
    else:
        print("\n[WARN] NVIDIA LLM connection failed. Fallback to rule-based...")

    if not license_result:
        print("\n[INFO] Running RULE-BASED license detection fallback...")
        license_result = detect_license_rule_based(preprocessed_text)
        if license_result:
            print("\n[OK] License detected by RULE-BASED engine")
            print(f"Matched keyword: {license_result.get('matched_keyword', '')}")
            print(f"Method: {license_result['method']}")
            print_license_result(license_result)
        else:
            print("\n[WARN] No license detected by rule-based engine.")
            license_result = {
                "license_name": "Unknown",
                "license_family": "Unknown",
                "copyright_holder": "",
                "copyright_status": "No license detected",
                "commercial_use": None,
                "modification_allowed": None,
                "redistribution_allowed": None,
                "attribution_required": None,
                "evidence": "",
                "confidence": 0.0,
                "method": "None"
            }
            print_license_result(license_result)

    # STEP 9: SAVE LICENSE RESULT
    save_license_result(license_result, pdf_path)

    # STEP 10: ADD LICENSE & FULL TEXT TO METADATA
    if isinstance(final_metadata, dict):
        final_metadata["license_detected"] = license_result.get("license_name", "Unknown")
        final_metadata["license_family"] = license_result.get("license_family", "")
        final_metadata["copyright_status"] = license_result.get("copyright_status", "")
        final_metadata["license_evidence"] = license_result.get("evidence", "")
        final_metadata["license_confidence"] = license_result.get("confidence", 0.0)
        final_metadata["detection_method"] = license_result.get("method", "")
        final_metadata["full_text"] = full_text
        final_metadata["text_sample"] = full_text[:3000] if full_text else ""

    # STEP 11: SAVE COMPLETE METADATA
    save_complete_metadata(final_metadata, license_result, pdf_path)


    # STEP 12: SAVE TO POSTGRESQL DATABASE
    print("\n========== SAVING TO POSTGRESQL ==========")
    save_to_postgres(final_metadata, license_result)

    print(f"\n[OK] COMPLETED PROCESSING FOR: {os.path.basename(pdf_path)}")


