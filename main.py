def detect_license_with_llm(license_text):

    if not license_text.strip():

        print(
            "\n[ERROR] No license evidence to send to LLM"
        )

        return None

    prompt = f"""
You are a professional copyright and license
detection engine.

Analyze ONLY the evidence provided below.

Your task is to determine the RESOURCE-SPECIFIC
license or copyright status of this particular
book/document.

IMPORTANT:

1. Do NOT assume that the website/platform/source
   has one license for all resources.

2. Determine the license only from the evidence
   provided.

3. Prefer an explicit license statement.

4. If Creative Commons is mentioned, identify
   the exact license.

5. Examples:

   CC BY 4.0
   CC BY-SA 4.0
   CC BY-NC 4.0
   CC BY-NC-SA 4.0
   CC BY-ND 4.0
   CC BY-NC-ND 4.0
   CC0 1.0
   Public Domain
   MIT
   Apache 2.0
   GPL
   LGPL
   GFDL
   Mozilla Public License

6. "All rights reserved" is NOT a Creative Commons
   or open license.

7. If the evidence clearly states only a copyright
   restriction such as:

   "All rights reserved"

   or

   "No part of this publication may be reproduced
   without prior permission"

   then:

   license_name = "Unknown"

   license_family = "Copyright"

   copyright_status = "All Rights Reserved"

8. If the evidence names a specific publisher or
   institution (for example NCERT) but also contains
   an explicit copyright restriction, prefer the
   copyright restriction and return:

   license_name = "Unknown"

   license_family = "Copyright"

   copyright_status = "All Rights Reserved"

9. Do NOT invent missing information.

10. If there is no explicit license:

    license_name = "Unknown"

11. Confidence must be between 0.0 and 1.0.

12. Return ONLY valid JSON.

Use EXACTLY this JSON structure:

{{
    "license_name": "",
    "license_family": "",
    "copyright_holder": "",
    "copyright_status": "",
    "commercial_use": null,
    "modification_allowed": null,
    "redistribution_allowed": null,
    "attribution_required": null,
    "evidence": "",
    "confidence": 0.0
}}

LICENSE / COPYRIGHT EVIDENCE:

{license_text}
"""

    print(
        "\n========== SENDING TO NVIDIA LLM (FALLBACK) =========="
    )

    print(
        f"Evidence length sent to LLM: "
        f"{len(license_text)} characters"
    )

    try:

        response = client.chat.completions.create(

            model=MODEL_NAME,

            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are a precise copyright "
                        "and license detection engine. "
                        "Return only valid JSON."
                    )
                },
                {
                    "role": "user",
                    "content": prompt
                }
            ],

            temperature=0.0,

            max_tokens=500
        )

        result = (
            response
            .choices[0]
            .message
            .content
        )

        print(
            "\n[OK] NVIDIA response received"
        )

        return result

    except Exception as error:

        print(
            "\n========== NVIDIA LLM ERROR =========="
        )

        print(
            type(error).__name__
        )

        print(
            str(error)
        )

        return None


