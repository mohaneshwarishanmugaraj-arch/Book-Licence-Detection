def parse_pdf(pdf_path):

    print("\n========== PDF PARSING ==========")

    if not os.path.exists(pdf_path):
        raise FileNotFoundError(
            f"PDF not found: {pdf_path}"
        )

    print(f"Input PDF: {pdf_path}")

    os.makedirs("output", exist_ok=True)

    try:

        opendataloader_pdf.convert(
            input_path=pdf_path,
            output_dir="output",
            format="json,markdown"
        )

        print("[OK] PDF parsing completed (Generated JSON, Markdown, and Images in output/)")

    except Exception as error:

        print("\n[ERROR] PDF PARSING ERROR")
        print(error)

        raise


def find_json_for_pdf(pdf_path):
    """
    Find the JSON file generated by OpenDataLoader for the given PDF path.
    Handles case-insensitive matching.
    """
    base_name = os.path.splitext(os.path.basename(pdf_path))[0]
    expected_exact = os.path.join("output", f"{base_name}.json")
    if os.path.exists(expected_exact):
        return expected_exact

    if os.path.exists("output"):
        for f in os.listdir("output"):
            if f.lower() == f"{base_name}.json".lower():
                return os.path.join("output", f)

    return expected_exact


