def save_license_result(
    result,
    pdf_path
):

    os.makedirs(
        "output",
        exist_ok=True
    )

    filename = os.path.basename(
        pdf_path
    )

    base_name = os.path.splitext(
        filename
    )[0]

    output_file = (
        f"output/"
        f"{base_name}_license_result.json"
    )

    final_data = {

        "document": {
            "filename": filename,
            "file_path": pdf_path
        },

        "license_detection": result,

        "processed_at":
            datetime.now().isoformat()
    }

    with open(
        output_file,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(
            final_data,
            file,
            indent=4,
            ensure_ascii=False
        )

    print(
        f"\n[OK] License result saved:"
    )

    print(
        output_file
    )


